package templates

import (
	"context"
	"fmt"

	"github.com/allanpk716/agent-taskboard/internal/identity"
)

// SeedIfEmpty 首次启动时预置三份模板（spec 用户故事 36：Bug 反馈、分配任务、
// 问题咨询，开箱即用）。已有任何模板就不再导入，保证是一次性的。
func (m *Manager) SeedIfEmpty(ctx context.Context) error {
	var known int
	if err := m.db.QueryRowContext(ctx, `SELECT COUNT(*) FROM templates`).Scan(&known); err != nil {
		return err
	}
	if known > 0 {
		return nil
	}
	for key, markdown := range seedTemplates {
		if _, err := m.Create(ctx, key, markdown, identity.Viewer{}); err != nil {
			return fmt.Errorf("预置模板 %s 导入失败：%w", key, err)
		}
	}
	return nil
}

